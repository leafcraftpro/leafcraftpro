/**
 * Render an icon as an inline SVG string.
 * @param {string} name   key from the PATHS map
 * @param {string} className optional class attribute
 * @param {number} size   pixel size (width and height)
 */
export function icon(name, className = '', size = 20) {
  const path = PATHS[name];
  if (!path) return '';
  const cls = className ? ` class="${className}"` : '';
  const filled = name === 'star';
  const attrs = filled
    ? 'fill="currentColor" stroke="none"'
    : 'fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round"';
  return (
    `<svg${cls} width="${size}" height="${size}" viewBox="0 0 24 24" ` +
    `${attrs} aria-hidden="true" focusable="false">${path}</svg>`
  );
}

export function hasIcon(name) {
  return Boolean(PATHS[name]);
}

